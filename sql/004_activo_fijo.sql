CREATE TABLE IF NOT EXISTS activos_fijos (
    id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    empresa_id INT NOT NULL,
    codigo_interno VARCHAR(30) NOT NULL,
    nombre VARCHAR(180) NOT NULL,
    categoria VARCHAR(80) NOT NULL,
    fecha_adquisicion DATE NOT NULL,
    fecha_puesta_marcha DATE NOT NULL,
    regimen_depreciacion ENUM('NORMAL', 'ACELERADA', 'INSTANTANEA_14D') NOT NULL DEFAULT 'NORMAL',
    vida_util_normal_meses INT NOT NULL,
    vida_util_aplicada_meses INT NOT NULL,
    meses_depreciados INT NOT NULL DEFAULT 0,
    valor_adquisicion DECIMAL(18,4) NOT NULL,
    correccion_monetaria_acum DECIMAL(18,4) NOT NULL DEFAULT 0.0000,
    depreciacion_acumulada DECIMAL(18,4) NOT NULL DEFAULT 0.0000,
    valor_residual DECIMAL(18,4) NOT NULL DEFAULT 1.0000,
    cuenta_activo_id INT NOT NULL,
    cuenta_dep_acumulada_id INT NOT NULL,
    cuenta_gasto_dep_id INT NOT NULL,
    estado ENUM('ACTIVO', 'DEPRECIADO_TOTAL', 'DADO_DE_BAJA', 'VENDIDO') NOT NULL DEFAULT 'ACTIVO',
    fecha_baja DATE NULL,
    motivo_baja VARCHAR(255) NULL,
    creado_por INT NOT NULL,
    creado_en DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE KEY uk_af_empresa_codigo (empresa_id, codigo_interno),
    INDEX idx_af_empresa_estado (empresa_id, estado)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS activo_fijo_movimientos (
    id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    empresa_id INT NOT NULL,
    activo_id INT NOT NULL,
    periodo_id INT NOT NULL,
    asiento_id INT NULL,
    tipo_movimiento ENUM('DEPRECIACION', 'BAJA') NOT NULL,
    fecha_movimiento DATE NOT NULL,
    variacion_ipc_pct DECIMAL(8,4) NOT NULL DEFAULT 0.0000,
    monto_reajuste_cm DECIMAL(18,4) NOT NULL DEFAULT 0.0000,
    meses_consumidos INT NOT NULL DEFAULT 0,
    monto_depreciacion DECIMAL(18,4) NOT NULL DEFAULT 0.0000,
    valor_libro_resultante DECIMAL(18,4) NOT NULL,
    creado_en DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE KEY uk_af_mov_periodo (activo_id, periodo_id, tipo_movimiento),
    INDEX idx_af_mov_empresa_periodo (empresa_id, periodo_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;